import { test, expect } from "@playwright/test";
import path from "node:path";

test("packaged sign-in, verification and journey creation flow", async ({ page, context }) => {
  const external: string[] = [], errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  await context.route("**/*", route => {
    const url = new URL(route.request().url());
    if (["127.0.0.1", "localhost"].includes(url.hostname)) return route.continue();
    external.push(url.href); return route.abort();
  });
  await page.goto("/");
  // Page opens directly on Sign in - click Create account link
  await expect(page.getByText("New to Meridian?")).toBeVisible();
  await page.getByRole("button", { name: /Create account/ }).click();
  await expect(page.getByRole("heading", { name: "Personal information" })).toBeVisible();
  await page.getByLabel("Full legal name").fill("USB Test Traveler");
  const passport = "X90817263";
  await page.getByLabel("Passport number", { exact: true }).fill(passport);
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Request code", exact: true }).click();
  await page.locator(".verification-delivery-panel summary").click();
  const code = (await page.locator(".verification-delivery-panel strong").innerText()).trim();
  expect(code).toMatch(/^\d{6}$/);
  const wrong = code === "000000" ? "111111" : "000000";
  await page.getByLabel("Six-digit local verification code").fill(wrong);
  await page.getByRole("button", { name: "Verify code", exact: true }).click();
  await expect(page.locator(".form-error")).toContainText("invalid or expired");
  await page.getByLabel("Six-digit local verification code").fill(code);
  await page.getByRole("button", { name: "Verify code", exact: true }).click();
  await expect(page.locator(".verification-status")).toBeVisible();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Create a journey", exact: true }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Journey name").fill("USB London study");
  await page.getByLabel("Destination city").fill("London");
  await page.getByRole("button", { name: /Add transit/ }).click();
  await page.getByLabel(/Transit (stop|point|country)/).last().fill("Doha");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByText("USB Test Traveler", { exact: true }).first()).toBeVisible();
  await expect(page.getByText("Maya Bennett", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: /Create journey|Generate travel plan/, exact: true }).click();
  await expect(page.locator(".app-content h1")).toHaveText("USB London study");
  await page.reload();
  await expect(page.locator(".app-content h1")).toHaveText("USB London study");
  const stored = await page.evaluate(() => localStorage.getItem("meridian-demo-v1")!);
  expect(stored).not.toContain(passport);
  const state = JSON.parse(stored);
  expect(state.travelers).toHaveLength(1);
  expect(state.journeys).toHaveLength(1);
  expect(state.travelers[0].name).toBe("USB Test Traveler");
  expect(state.travelers[0].nationality).toBe("India");
  expect(state.travelers[0].passportMasked).toContain("••••");
  await page.goto("/app/entry");
  await expect(page.locator(".requirements-table")).toContainText(/Student|study/);
  await expect(page.locator(".app-content")).toContainText("Official confirmation required");
  await page.goto("/app/ai");
  await page.getByLabel("Ask Meridian").fill("journey summary");
  await page.getByLabel("Ask Meridian").press("Enter");
  await expect(page.locator(".message.assistant")).toContainText("USB London study");
  expect(external).toEqual([]);
  expect(errors).toEqual([]);
});

test("requesting a new code invalidates the previous challenge", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: /Create account/ }).click();
  await page.getByLabel("Full legal name").fill("Code Test");
  await page.getByLabel("Passport number", { exact: true }).fill("AB123456");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Request code", exact: true }).click();
  await page.locator(".verification-delivery-panel summary").click();
  const code = await page.locator(".verification-delivery-panel strong").innerText();
  await page.getByRole("button", { name: "Resend local code" }).click();
  await expect(page.getByRole("button", { name: "Requesting…" })).toHaveCount(0);
  await page.getByLabel("Six-digit local verification code").fill(code);
  await page.getByRole("button", { name: "Verify code", exact: true }).click();
  await expect(page.locator(".form-error")).toContainText("invalid or expired");
});

test("offline map selection, zoom, pan and light/dark styles work in the package", async ({ page, context }) => {
  const errors: string[] = [], external: string[] = [], failed: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("response", r => { if (r.status() >= 400) failed.push(r.url()); });
  await context.route("**/*", route => {
    if (["127.0.0.1", "localhost"].includes(new URL(route.request().url()).hostname)) return route.continue();
    external.push(route.request().url()); return route.abort();
  });
  await page.goto("/");
  await expect(page.getByText("New to Meridian?")).toBeVisible();
  await page.getByRole("button", { name: /Create account/ }).click();
  await page.getByLabel("Full legal name").fill("Map Test");
  await page.getByLabel("Passport number", { exact: true }).fill("AB123456");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Request code", exact: true }).click();
  await page.locator(".verification-delivery-panel summary").click();
  const code = (await page.locator(".verification-delivery-panel strong").innerText()).trim();
  await page.getByLabel("Six-digit local verification code").fill(code);
  await page.getByRole("button", { name: "Verify code", exact: true }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Create a journey", exact: true }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Journey name").fill("Map journey");
  await page.getByLabel("Destination city").fill("London");
  await page.getByRole("button", { name: /Add transit/ }).click();
  await page.getByLabel(/Transit (stop|point|country)/).last().fill("Doha");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: /Create journey|Generate travel plan/, exact: true }).click();
  await page.goto("/app/travel");
  await expect(page.locator(".geo-map svg")).toBeVisible();
  await expect(page.locator(".geo-flight")).toHaveCount(2);
  await page.locator(".geo-segments button").first().click();
  await expect(page.locator(".geo-flight.selected")).toHaveCount(1);
  const svg = page.locator(".geo-map > svg");
  const box = await svg.getAttribute("viewBox");
  await page.getByRole("button", { name: "Zoom in map" }).click();
  await expect(svg).not.toHaveAttribute("viewBox", box!);
  const zoomed = await svg.getAttribute("viewBox");
  const bounds = (await svg.boundingBox())!;
  await page.mouse.move(bounds.x + 50, bounds.y + 50);
  await page.mouse.down(); await page.mouse.move(bounds.x + 100, bounds.y + 80); await page.mouse.up();
  await expect(svg).not.toHaveAttribute("viewBox", zoomed!);
  await page.getByRole("button", { name: "Reset map view" }).click();
  await page.getByRole("button", { name: "Toggle theme" }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  expect(errors).toEqual([]); expect(external).toEqual([]); expect(failed).toEqual([]);
});

